/// นาฬิกาของแอป — มีไว้เพื่อ "ตรึงเวลา" ตอนถ่ายภาพหน้าจอและตอนเขียนเทสต์
///
/// โค้ดส่วนไหนที่ผลลัพธ์บนจอขึ้นกับเวลาปัจจุบัน ให้เรียกผ่าน [now] แทนการ
/// เรียก `DateTime.now()` ตรง ๆ เพราะไม่อย่างนั้นภาพหน้าจอที่ถ่ายซ้ำจะได้ไฟล์
/// ไม่เหมือนเดิมทุกครั้ง (เวลาบนการ์ดออเดอร์เลื่อนไปเรื่อย ๆ) กลายเป็น diff
/// ปลอมใน git ที่แยกไม่ออกว่าอันไหนคือการเปลี่ยนแปลงจริงของ UI
///
/// ที่ที่ "ไม่" ต้องใช้: `initialDate` ของ date picker และการออก id ที่ไม่ได้
/// เอาไปแสดงผล — พวกนี้ไม่กระทบภาพที่ถ่ายได้
class AppClock {
  const AppClock._();

  static DateTime Function() _source = DateTime.now;

  /// เวลาปัจจุบัน — ค่าเริ่มต้นคือนาฬิกาจริงของเครื่อง
  static DateTime now() => _source();

  /// ตรึงเวลาไว้ที่จุดเดียว ใช้เฉพาะในเทสต์และสคริปต์ถ่ายภาพหน้าจอ
  /// อย่าเรียกจากโค้ดที่รันจริง
  static void freeze(DateTime at) => _source = () => at;

  /// กลับไปใช้นาฬิกาจริง — เรียกใน tearDown เสมอ ไม่งั้นเวลาที่ตรึงไว้จะรั่ว
  /// ไปถึงเทสต์ตัวถัดไป (static ใช้ร่วมกันทั้ง process)
  static void unfreeze() => _source = DateTime.now;
}
