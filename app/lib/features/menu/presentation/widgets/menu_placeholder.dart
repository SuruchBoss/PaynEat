import 'package:flutter/material.dart';

/// ภาพแทนของเมนูที่ยังไม่ได้ใส่รูป
///
/// ของเดิมเอา "อักษรตัวแรก" ของชื่อเมนูมาแปะตัวใหญ่บนพื้นไล่สี ซึ่งใช้ได้เฉพาะ
/// ภาษาที่ตัวอักษรเดี่ยวยังดูเป็นลวดลาย — ภาษาไทย "ข" จาก "ข้าวผัดกุ้ง" ผ่าน
/// แต่ภาษาเกาหลีได้ "돼" จาก "돼지고기 랏나" ซึ่งเป็น **เศษคำ** ไม่ใช่ตัวอักษร
/// คนเกาหลีอ่านแล้วสะดุดทันทีเหมือนเห็นป้ายเขียนว่า "ก๋ว" แล้วจบ
/// (ผู้ใช้ชาวเกาหลีทักเรื่องนี้เป็นข้อแรกตอนเปิดดูหน้าจริง)
///
/// ภาพแทนใหม่จึงไม่พึ่งตัวอักษรเลย — ใช้สัญลักษณ์ช้อนส้อมกลางพื้นสีเรียบ
/// ส่วน "สี" เป็นโทนอาหารเรียบ ๆ ที่สุ่มจากตัวเมนู (เมนูเดิมได้สีเดิมเสมอ)
/// ไว้ให้จอมีจังหวะ ไม่ได้อ้างว่าสีบอกว่าเมนูนั้นเป็นอาหารประเภทไหน —
/// การเดาประเภทอาหารจากชื่อแล้วเลือกไอคอนให้ เดาผิดเมื่อไหร่ดูสะเพร่ากว่าเดิม
class MenuPlaceholder extends StatelessWidget {
  const MenuPlaceholder({super.key, required this.seed, this.compact = false});

  /// ใช้เลือกสี — เมนูเดิมได้สีเดิมเสมอ ไม่กระพริบเปลี่ยนสีตอน rebuild
  ///
  /// เคยผูกกับ `categoryId` ด้วยเหตุผลว่า "สีจะได้สื่อถึงหมวด" แต่พอถ่ายภาพจริง
  /// พบว่าเมนูหมวดเดียวกัน 5 ใบเรียงกันได้สีเดียวกันหมด จอเลยดูจืดผิดปกติ
  /// และลูกค้าก็กรองด้วยชิปหมวดอยู่แล้ว สีจึงไม่ได้บอกอะไรเพิ่ม
  final int seed;

  /// true สำหรับรูปเล็กในแถวจัดการเมนู (ไอคอนเล็กลงตาม)
  final bool compact;

  /// โทนสีสำหรับร้านอาหาร: เบจ/เซจ/ดินเผา/หินชนวน/มะกอก/ม่วงหม่น
  ///
  /// จงใจเลี่ยงสีไล่โทนสดแบบเดิม (ชมพู-ส้ม-ฟ้านีออน) ซึ่งอ่านเป็นแอปเด็ก
  /// มากกว่าร้านอาหาร — แอปสั่งอาหารเกาหลีที่คนใช้จริงใช้รูปอาหารจริง
  /// หรือไม่ก็พื้นเรียบสีเดียว ไม่มีเจ้าไหนใช้ไล่สีจัดจ้าน
  static const List<(Color bg, Color fg)> _tones = [
    (Color(0xFFF4EFE7), Color(0xFF8A7454)), // เบจอุ่น
    (Color(0xFFEAF0EC), Color(0xFF5E7E6A)), // เซจ
    (Color(0xFFF5EDE9), Color(0xFF8F6E60)), // ดินเผา
    (Color(0xFFE9EEF3), Color(0xFF5F7689)), // หินชนวน
    (Color(0xFFF2F1E6), Color(0xFF787653)), // มะกอก
    (Color(0xFFEFEDF4), Color(0xFF6E6B87)), // ม่วงหม่น
  ];

  (Color, Color) get _tone => _tones[seed.abs() % _tones.length];

  @override
  Widget build(BuildContext context) {
    final (bg, fg) = _tone;
    return ColoredBox(
      color: bg,
      child: Center(
        child: Icon(
          Icons.restaurant_rounded,
          size: compact ? 18 : 28,
          color: fg.withValues(alpha: 0.55),
        ),
      ),
    );
  }
}
